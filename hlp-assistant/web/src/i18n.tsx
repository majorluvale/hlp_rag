const dicts: Record<Lang, Record<Key, string>> = { en, fr };

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'en' || v === 'fr') return v;
  } catch {
    /* storage unavailable */
  }
  return DEFAULT_LANG;
}

/** Current UI language, readable outside React (used by the API client). */
let currentLang: Lang = readStoredLang();
export const getLang = () => currentLang;

/** Acronym and product name per language: HLP in English, LTP in French. */
export const ACRONYM: Record<Lang, string> = { en: 'HLP', fr: 'LTP' };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
}

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(currentLang);
  const setLang = useCallback((l: Lang) => {
    currentLang = l;
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = useCallback<T>(
    (key, vars) => {
      let s = dicts[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error('I18nProvider missing');
  return c;
}

export function timeAgoT(t: T, ms: number, lang: Lang) {
  const d = (Date.now() - ms) / 1000;
  if (d < 60) return t('time.now');
  if (d < 3600) return t('time.min', { n: Math.floor(d / 60) });
  if (d < 86400) return t('time.h', { n: Math.floor(d / 3600) });
  if (d < 86400 * 7) return t('time.d', { n: Math.floor(d / 86400) });
  return new Date(ms).toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-GB');
}
